def lever(m, key, base, axis, turn_axis, degrees, length, flags=""):
    """A lever standing up from the desk at `base`, hinged on a marker along
    `axis` there; it turns `degrees` about `turn_axis` at full travel (a
    positive turn about +Z tips it forward, toward −X)."""
    x, y, z = base
    i = "xyz".index(axis)
    a, b = list(base), list(base)
    a[i] += 0.05 if base[i] >= 0 else -0.05
    b[i] -= 0.05 if base[i] >= 0 else -0.05
    a, b = tuple(a), tuple(b)
    m.add(f"{key}_ROT_{rot_degrees(a, b, turn_axis, degrees)}", "steel", line(a, b))
    m.add(f"{key}_LEVER{flags}", "black", box((x - 0.015, y, z - 0.015), (x + 0.015, y + length, z + 0.015)))
    m.add(f"{key}_KNOB", "knob", box((x - 0.035, y + length, z - 0.035), (x + 0.035, y + length + 0.06, z + 0.035)))


def rotary(m, key, base, arm, degrees, length):
    """A brake valve handle turning about the vertical through `base`: an arm
    pointing along `arm`, `degrees` (about +Y) at full travel."""
    x, y, z = base
    a, b = (x, y - 0.02, z), (x, y + 0.08, z)
    m.add(f"{key}_ROT_{rot_degrees(a, b, (0.0, 1.0, 0.0), degrees)}", "steel", line(a, b))
    tip = add((x, y + 0.06, z), mul(arm, length))
    m.add(f"{key}_HANDLE", "black", beam((x, y + 0.06, z), tip, 0.03, 0.03, (0.0, 1.0, 0.0))
          + cylinder("y", (z, x), 0.03, y, y + 0.08, sides=8))
    m.add(f"{key}_KNOB", "knob", cylinder("y", (tip[2], tip[0]), 0.03, tip[1] - 0.02, tip[1] + 0.05, sides=8))


