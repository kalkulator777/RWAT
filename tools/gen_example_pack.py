"""gen_example_pack — write the RWAT example pack (roadmap R11).

The pack shows every function of pack format 1 on stock of its own, under
CC0 1.0: a passenger coach with a walkable interior, a shunting locomotive
with a walkable cab and working controls, a two-axle wagon and a rail style.
Every model is procedural — boxes and cylinders named by the IR convention
(schema/obj-conventions.json) — every texture a few coloured pixels written
here, every sound a vanilla sound event (minecraft:…). No third-party asset
goes in. It looks rough on purpose: it is a reference for the author's guide
(docs/pack-format.md), the pack editor and the tests, not a showcase.

    python -I tools/gen_example_pack.py             writes run/rwat_packs/RwatExamplePack
    python -I tools/gen_example_pack.py --out DIR   writes DIR instead

The pack is generated, never edited by hand: change this script and run it.
It replaces only a folder it wrote itself (pack.mcmeta naming this pack) or
an empty one. The output is the same bytes on every run and platform: no
clock, no randomness, no libm (sines and cosines are a series here), PNGs
stored uncompressed (zlib builds compress differently).
tools/tests/test_example_pack.py holds the committed pack to it.

Markup — floor zones, doors, driver's chairs — is in the OBJ frame of
format 1 (docs/pack-format.md §3): x along the wagon with the front at −X,
y up with the wheel tread's bottom (the railhead) at y = −0.03 and the axles
at y = 0.5, z across with +Z the left side going forward; the same numbers
as the OBJ vertices, so a box of the markup can be checked against the model
(the GUIDE_ objects of the coach and the shunter draw it, skipped in game).

Python 3.9+, standard library only.
"""

