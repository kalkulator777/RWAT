# ------------------------------------------------------------------ numbers

def num(x, places=4):
    """A number as the OBJ, MTL and .anim files write it: fixed places, never -0."""
    text = f"{x:.{places}f}"
    return f"{0.0:.{places}f}" if float(text) == 0.0 else text


def sin_cos(degrees):
    """(sin, cos) of an angle in degrees by Taylor series: only + − × ÷ on
    floats, so the same bits on every platform (libm's last bit is not)."""
    turns = degrees % 360.0
    quarter = int(turns // 90.0)
    x = (turns - 90.0 * quarter) * (math.pi / 180.0)
    x2 = x * x
    s = term_s = x
    c = term_c = 1.0
    for n in range(1, 13):
        term_s = -term_s * x2 / ((2 * n) * (2 * n + 1))
        term_c = -term_c * x2 / ((2 * n - 1) * (2 * n))
        s += term_s
        c += term_c
    for _ in range(quarter):
        s, c = c, -s          # sin(90° + a) = cos a, cos(90° + a) = −sin a
    return s, c


def add(a, b):
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def mul(a, k):
    return (a[0] * k, a[1] * k, a[2] * k)


def dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def unit(a):
    length = math.sqrt(dot(a, a))
    return (0.0, 1.0, 0.0) if length < 1e-12 else mul(a, 1.0 / length)


def newell(points):
    """The (unnormalised) normal of a polygon, by Newell's method."""
    n = [0.0, 0.0, 0.0]
    for i, p in enumerate(points):
        q = points[(i + 1) % len(points)]
        n[0] += (p[1] - q[1]) * (p[2] + q[2])
        n[1] += (p[2] - q[2]) * (p[0] + q[0])
        n[2] += (p[0] - q[0]) * (p[1] + q[1])
    return tuple(n)


def centroid(points):
    k = 1.0 / len(points)
    return (sum(p[0] for p in points) * k, sum(p[1] for p in points) * k, sum(p[2] for p in points) * k)


# ------------------------------------------------------------------ solids
#
# A solid is a list of faces, each a list of points; solid() turns every face
# outward (from the solid's centre) so its normal lights it right.

def solid(faces):
    corners = sorted({p for face in faces for p in face})
    middle = centroid(corners)
    out = []
    for face in faces:
        if dot(newell(face), sub(centroid(face), middle)) < 0:
            face = face[::-1]
        out.append(face)
    return out


def box(lo, hi):
    (x0, y0, z0), (x1, y1, z1) = lo, hi
    assert x0 < x1 and y0 < y1 and z0 < z1, (lo, hi)
    c = [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1),
         (x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)]
    return solid([[c[0], c[1], c[2], c[3]], [c[4], c[7], c[6], c[5]], [c[0], c[4], c[5], c[1]],
                  [c[1], c[5], c[6], c[2]], [c[2], c[6], c[7], c[3]], [c[3], c[7], c[4], c[0]]])


AXES = {"x": (1, 2, 0), "y": (2, 0, 1), "z": (0, 1, 2)}  # in-plane (i, j) and the extrusion axis k


def point(axis, i, j, k):
    """A point from its coordinates in the frame of `axis` (see AXES)."""
    ai, aj, ak = AXES[axis]
    p = [0.0, 0.0, 0.0]
    p[ai], p[aj], p[ak] = i, j, k
    return tuple(p)


def prism(axis, profile, k0, k1):
    """A convex profile [(i, j), …] extruded along `axis` from k0 to k1."""
    near = [point(axis, i, j, k0) for i, j in profile]
    far = [point(axis, i, j, k1) for i, j in profile]
    faces = [near, far[::-1]]
    for m in range(len(profile)):
        n = (m + 1) % len(profile)
        faces.append([near[m], near[n], far[n], far[m]])
    return solid(faces)


def cylinder(axis, centre, radius, k0, k1, sides=16):
    """A cylinder along `axis` around centre (i, j) of the AXES frame."""
    profile = []
    for m in range(sides):
        s, c = sin_cos(360.0 * m / sides)
        profile.append((centre[0] + radius * c, centre[1] + radius * s))
    return prism(axis, profile, k0, k1)


def beam(a, b, width, thick, normal):
    """A box from point a to point b, `width` wide and `thick` thick along `normal`."""
    d = unit(sub(b, a))
    side = mul(unit(cross(d, normal)), width / 2.0)
    up = mul(unit(normal), thick / 2.0)
    c = [add(add(p, s), u) for p in (a, b) for s in (side, mul(side, -1.0)) for u in (up, mul(up, -1.0))]
    # c: a+s+u, a+s−u, a−s+u, a−s−u, b+s+u, b+s−u, b−s+u, b−s−u
    return solid([[c[0], c[1], c[3], c[2]], [c[4], c[6], c[7], c[5]], [c[0], c[4], c[5], c[1]],
                  [c[2], c[3], c[7], c[6]], [c[0], c[2], c[6], c[4]], [c[1], c[5], c[7], c[3]]])


def panel(normal_axis, t0, t1, u0, u1, y0, y1, holes=()):
    """A wall between t0 and t1 along `normal_axis` ("x" or "z"), spanning u0..u1
    along the other horizontal axis and y0..y1, with rectangular holes
    (u0, u1, y0, y1) cut through: the solid cells as boxes."""
    us = sorted({u0, u1} | {h[0] for h in holes} | {h[1] for h in holes})
    faces = []
    for ua, ub in zip(us, us[1:]):
        crossing = [h for h in holes if h[0] <= ua and h[1] >= ub]
        ys = sorted({y0, y1} | {h[2] for h in crossing} | {h[3] for h in crossing})
        run = None
        for ya, yb in zip(ys, ys[1:]):
            open_cell = any(h[2] <= ya and h[3] >= yb for h in crossing)
            if not open_cell:
                run = (run[0], yb) if run else (ya, yb)
            if open_cell or yb == ys[-1]:
                if run:
                    if normal_axis == "x":
                        faces += box((t0, run[0], ua), (t1, run[1], ub))
                    else:
                        faces += box((ua, run[0], t0), (ub, run[1], t1))
                run = None
    return faces


def line(a, b):
    """A pivot marker: a face with only two corners, the hinge's axis from a to b.

    A control's …_ROT marker gives the hinge (docs/pack-format.md §9,
    PivotAxis): the centre of its bounding box and its long direction, from
    the end nearer the OBJ origin to the far one. Two points make that exact;
    the face has no area, so nothing of it is drawn; its material is textured
    all the same, though an untextured marker, as IR's packs have them, is as
    good (the engine reads its axis either way, the pack check doesn't warn)."""
    return [[a, b, b, a]]


def axis_from(a, b):
    """Which way a line marker's hinge points: from its end nearer the origin."""
    near, far = (a, b) if dot(a, a) < dot(b, b) else (b, a)
    return unit(sub(far, near))


def rot_degrees(a, b, wanted_axis, degrees):
    """The ROT angle for a marker a–b so the part turns `degrees` about `wanted_axis`
    (right-handed): negated when the marker's own axis points the other way."""
    sign = dot(axis_from(a, b), wanted_axis)
    assert abs(abs(sign) - 1.0) < 1e-9, (a, b, wanted_axis)
    value = degrees if sign > 0 else -degrees
    return f"{value:g}"


# ------------------------------------------------------------------ OBJ and MTL

class Model:
    """One OBJ under construction: named objects of textured faces, and its MTL."""

    def __init__(self, name):
        self.name = name             # file stem: <name>.obj, <name>.mtl
        self.objects = []            # [object name, material, [(points, uvs, normal)]]
        self.materials = {}          # material → texture path relative to the OBJ

    def material(self, name, texture):
        assert self.materials.get(name, texture) == texture, name
        self.materials[name] = texture

    def add(self, obj, material, faces, uv=None):
        """Faces (from the solids above) into object `obj`; uv: None = each face
        spans its texture, ("band", y0, y1) = v follows the height y0..y1."""
        assert material in self.materials, material
        if not self.objects or self.objects[-1][0] != obj or self.objects[-1][1] != material:
            assert all(o[0] != obj or o[1] != material for o in self.objects), f"{obj} split in two"
            self.objects.append([obj, material, []])
        for face in faces:
            n = newell(face)
            self.objects[-1][2].append((face, face_uvs(face, n, uv), unit(n)))

    def obj_bytes(self):
        lines = ["# " + HEADER, f"mtllib {self.name}.mtl"]
        vs, vts, vns = {}, {}, {}

        def index(table, prefix, text):
            if text not in table:
                table[text] = len(table) + 1
                lines.append(f"{prefix} {text}")
            return table[text]

        previous = None
        for obj, material, faces in self.objects:
            if obj != previous:
                lines.append(f"o {obj}")
            previous = obj
            lines.append(f"usemtl {material}")
            for points, uvs, normal in faces:
                n = index(vns, "vn", " ".join(num(c) for c in normal))
                refs = []
                for p, t in zip(points, uvs):
                    v = index(vs, "v", " ".join(num(c) for c in p))
                    vt = index(vts, "vt", " ".join(num(c) for c in t))
                    refs.append(f"{v}/{vt}/{n}")
                lines.append("f " + " ".join(refs))
        return ("\n".join(lines) + "\n").encode("ascii")

    def mtl_bytes(self):
        lines = ["# " + HEADER]
        for material, texture in self.materials.items():
            lines += ["", f"newmtl {material}", "Kd 1.0000 1.0000 1.0000", f"map_Kd {texture}"]
        return ("\n".join(lines) + "\n").encode("ascii")


def face_uvs(face, normal, uv):
    """Planar UVs: a vertical face maps its horizontal extent to u and y to v,
    a horizontal one x to u and z to v; each spans 0..1 unless v follows a band."""
    ax = max(range(3), key=lambda i: abs(normal[i]))
    ui, vi = {0: (2, 1), 1: (0, 2), 2: (0, 1)}[ax]
    lo = [min(p[i] for p in face) for i in range(3)]
    hi = [max(p[i] for p in face) for i in range(3)]

    def span(p, i):
        return 0.5 if hi[i] - lo[i] < 1e-9 else (p[i] - lo[i]) / (hi[i] - lo[i])

    out = []
    for p in face:
        u = span(p, ui)
        if uv is None:
            v = span(p, vi)
        else:
            _, y0, y1 = uv
            v = min(1.0, max(0.0, (p[1] - y0) / (y1 - y0)))
        out.append((u, v))
    return out


# ------------------------------------------------------------------ PNG

def png(rows):
    """An indexed-colour PNG of rows of (r, g, b), its zlib stream stored."""
    palette = {}
    raw = bytearray()
    for row in rows:
        raw.append(0)  # filter: none
        for rgb in row:
            raw.append(palette.setdefault(rgb, len(palette)))
    assert len(palette) <= 256
    height, width = len(rows), len(rows[0])

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 3, 0, 0, 0))
            + chunk(b"PLTE", b"".join(bytes(rgb) for rgb in palette))
            + chunk(b"IDAT", stored_zlib(bytes(raw)))
            + chunk(b"IEND", b""))


def stored_zlib(data):
    """A zlib stream of stored (uncompressed) deflate blocks."""
    out = bytearray(b"\x78\x01")
    for start in range(0, len(data), 65535):
        block = data[start:start + 65535]
        out.append(1 if start + 65535 >= len(data) else 0)
        out += struct.pack("<HH", len(block), len(block) ^ 0xFFFF) + block
    return bytes(out + struct.pack(">I", zlib.adler32(data) & 0xFFFFFFFF))


def rgb(hex_colour):
    return ((hex_colour >> 16) & 255, (hex_colour >> 8) & 255, hex_colour & 255)


def shade(colour, k):
    return tuple(max(0, min(255, int(round(c * k)))) for c in colour)


def image(width, height, pixel):
    return png([[pixel(x, y) for x in range(width)] for y in range(height)])


def tex_plain(colour, size=16, edge=0.8):
    """A colour with a darker one-pixel edge: boxes read as outlined."""
    base, rim = rgb(colour), shade(rgb(colour), edge)
    return image(size, size, lambda x, y: rim if x in (0, size - 1) or y in (0, size - 1) else base)


def tex_bands(bands, base, width=16, height=64):
    """Horizontal bands for a band-mapped body: [(v0, v1, colour)], v up from the bottom."""
    def pixel(x, y):
        v = 1.0 - (y + 0.5) / height
        for v0, v1, colour in bands:
            if v0 <= v < v1:
                return rgb(colour)
        return rgb(base)
    return image(width, height, pixel)


def tex_noise(base, spread, seed, size=32):
    """Speckled (ballast, coal): a fixed linear congruential sequence, no randomness."""
    state = seed
    rows = []
    for _ in range(size):
        row = []
        for _ in range(size):
            state = (state * 1103515245 + 12345) & 0x7FFFFFFF
            row.append(shade(rgb(base), 1.0 + spread * ((state >> 16) % 7 - 3) / 3.0))
        rows.append(row)
    return png(rows)


def tex_grid(base, rule, step, size=16):
    return image(size, size, lambda x, y: rgb(rule) if x % step == 0 or y % step == 0 else rgb(base))


def tex_stripes(a, b, period, size=32):
    """Diagonal hazard stripes."""
    return image(size, size, lambda x, y: rgb(a) if ((x + y) // period) % 2 == 0 else rgb(b))


def tex_vertical_slats(base, slot, size=16):
    return image(size, size, lambda x, y: rgb(slot) if x % 4 == 0 else rgb(base))


def tex_wood(size=16):
    """Sleeper wood: grain lines along u."""
    return image(size, size, lambda x, y: rgb(0x5A3D24) if y % 5 == 2 else rgb(0x6E4A2C))


def tex_dial(sweep_from, sweep, ticks, size=64):
    """A gauge face: white disc, black ring and ticks from sweep_from, clockwise
    over sweep degrees (0 = 12 o'clock); left-right symmetric so it reads the
    same mirrored."""
    pixels = [[rgb(0x303030)] * size for _ in range(size)]
    centre = (size - 1) / 2.0
    radius = size / 2.0 - 1.0
    for y in range(size):
        for x in range(size):
            r = math.sqrt((x - centre) ** 2 + (y - centre) ** 2)
            if r <= radius:
                pixels[y][x] = rgb(0x101010) if r > radius - 2.0 else rgb(0xF4F1E8)
    for t in range(ticks + 1):
        s, c = sin_cos(sweep_from + sweep * t / ticks)
        for step in range(int(radius * 0.62), int(radius - 2.0)):
            px, py = int(round(centre + step * s)), int(round(centre - step * c))
            pixels[py][px] = rgb(0x101010)
    return png(pixels)


def tex_handwheel(size=32):
    """A handwheel seen face on: rim and four spokes, so its turning shows."""
    centre = (size - 1) / 2.0
    radius = size / 2.0 - 1.0

    def pixel(x, y):
        dx, dy = x - centre, y - centre
        r = math.sqrt(dx * dx + dy * dy)
        if r > radius:
            return rgb(0x2A2A2A)
        if r > radius - 3.0 or r < 3.0 or abs(dx) < 1.5 or abs(dy) < 1.5:
            return rgb(0xB8241C)
        return rgb(0x2A2A2A)
    return image(size, size, pixel)


def tex_icon(size=64):
    """pack.png: a shunter on a track under a sky."""
    def pixel(x, y):
        if y >= 52:
            return rgb(0x7A7A72) if y >= 56 else rgb(0x5A3D24) if x % 6 < 3 else rgb(0x8A8A82)
        if 46 <= y < 52 and any(abs(x - cx) <= 3 for cx in (14, 22, 42, 50)):
            return rgb(0x202020)
        if 40 <= y < 46 and 6 <= x < 58:
            return rgb(0x303030)
        if 22 <= y < 40 and 34 <= x < 50:
            return rgb(0x9FC9E8) if 25 <= y < 31 and (37 <= x < 41 or 43 <= x < 47) else rgb(0xD9731F)
        if 28 <= y < 40 and (8 <= x < 34 or 50 <= x < 56):
            return rgb(0xD9731F)
        return rgb(0x8EC5F0)
    return image(size, size, pixel)


