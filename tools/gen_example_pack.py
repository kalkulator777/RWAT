def salon_door_anim():
    """The salon door's .anim (IR format): per frame, each object's transform
    relative to its rest pose, row-major, in the OBJ's own space — here a
    turn about the hinge at x −7.85, z −0.45, 0° … 90° into the salon."""
    hx, hz = -7.85, -0.45
    lines = []
    for obj in ("SALON_DOOR_LEAF_INTERIOR_LCG_IL", "SALON_DOOR_KNOB"):
        lines += [f"O {obj}", f"A {obj}Action"]
        for frame in range(13):
            s, c = sin_cos(7.5 * frame)
            tx = hx - (c * hx + s * hz)
            tz = hz - (-s * hx + c * hz)
            matrix = [c, 0.0, s, tx, 0.0, 1.0, 0.0, 0.0, -s, 0.0, c, tz, 0.0, 0.0, 0.0, 1.0]
            lines.append("M " + ",".join(num(v, 6) for v in matrix))
    return ("\n".join(lines) + "\n").encode("ascii")


