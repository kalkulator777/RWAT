def gauge(model, dials, key, centre, radius, facing, sweep_from, sweep, range_name=None):
    """A dial gauge on a desk panel facing +X or −X (facing = ±1): its face
    goes to `dials` (drawn later as one object lit with the desk lights), its
    needle and hinge marker are the gauge. The needle rests at sweep_from
    (clockwise from 12 o'clock as the driver sees it) and turns `sweep`
    degrees clockwise at full reading."""
    x, y, z = centre
    face0, face1 = sorted((x, x + facing * 0.005))
    dials += cylinder("x", (y, z), radius, face0, face1, sides=24)
    # the driver looks along −facing·X: their right is −facing·Z
    s, c = sin_cos(sweep_from)
    right = -facing
    nx = x + facing * 0.009
    tip = (nx, y + radius * 0.85 * c, z + right * radius * 0.85 * s)
    hub = (nx, y, z)
    a, b = (x + facing * 0.004, y, z), (x + facing * 0.014, y, z)
    # clockwise as seen: a negative turn about the axis that points at the viewer (+facing·X)
    degrees = rot_degrees(a, b, (float(facing), 0.0, 0.0), -sweep)
    model.add(f"{key}_ROT_{degrees}", "dark_steel", line(a, b))
    needle = f"{key}_NEEDLE" + (f"_RANGE_{range_name}" if range_name else "")
    model.add(needle, "needle", beam(hub, tip, 0.012, 0.004, (1.0, 0.0, 0.0)))


