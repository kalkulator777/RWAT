/**
 * «Переименовать и переписать ссылки» in the checks tab (docs/proposals/editor.md §2.1, M6):
 * shown while the pack has files with paths Minecraft refuses (the loader's
 * `loader.resource-path` findings). The button lists what would change — the files to
 * rename, the references to rewrite, the files left as they are and why — and only
 * «Применить» does it, as one command of the journal: Ctrl+Z gives every file back.
 */

import { useEffect, useRef } from 'preact/hooks';
import { t } from '../../i18n';
import { PythonProgress } from './PythonProgress';
import { createRepair, type Repair, type RepairPack, type RunCommand } from './repair';
import { isEmptyPlan, referenceCount, type RenamePlan } from './rename';
import '../common/section.css';
import './suggest.css';

/** How many entries of a list the plan shows before «и ещё N». */
const SHOWN = 30;

function List<T>({ items, label, children }: { items: readonly T[]; label: string; children: (item: T) => preact.ComponentChild }) {
  if (items.length === 0) return null;
  return (
    <div>
      <h4 class="tool-heading">{label}</h4>
      <ul>
        {items.slice(0, SHOWN).map((item, i) => (
          <li key={i} class="tool-note">
            {children(item)}
          </li>
        ))}
        {items.length > SHOWN && <li class="tool-note">{t('tools.suggest.rename.more', { count: items.length - SHOWN })}</li>}
      </ul>
    </div>
  );
}

function Plan({ plan, changed, repair, pack, busy, readOnly }: { plan: RenamePlan; changed: boolean; repair: Repair; pack: RepairPack; busy: boolean; readOnly: boolean }) {
  const refs = referenceCount(plan);
  return (
    <div class="suggest-repair-plan" data-testid="repair-plan" data-files={plan.renames.length} data-refs={refs}>
      {changed && (
        <p class="tool-note tool-warning" role="alert">
          {t('tools.suggest.rename.changed')}
        </p>
      )}
      <p class="tool-note">{t('tools.suggest.rename.summary', { files: plan.renames.length, refs })}</p>
      <List items={plan.renames} label={t('tools.suggest.rename.files', { count: plan.renames.length })}>
        {({ from, to }) => (
          <>
            <code>{from}</code> → <code>{to}</code>
          </>
        )}
      </List>
      <List items={plan.texts.flatMap((text) => Object.entries(text.moved).map(([from, to]) => ({ file: text.target, keyword: text.keyword, from, to })))} label={t('tools.suggest.rename.texts')}>
        {({ file, keyword, from, to }) => (
          <>
            <code>{file}</code>: {keyword} <code>{from}</code> → <code>{to}</code>
          </>
        )}
      </List>
      <List items={plan.jsons} label={t('tools.suggest.rename.jsons')}>
        {({ file, at, from, to }) => (
          <>
            <code>
              {file} {at}
            </code>
            : <code>{from}</code> → <code>{to}</code>
          </>
        )}
      </List>
      <List items={plan.skipped} label={t('tools.suggest.rename.skipped', { count: plan.skipped.length })}>
        {({ path, reason, to }) => (
          <>
            <code>{path}</code> — {t(`tools.suggest.rename.skip.${reason}`, { to: to ?? '' })}
          </>
        )}
      </List>
      <List items={plan.notes} label={t('tools.suggest.rename.notes')}>
        {(note) => (note.kind === 'shared' ? t('tools.suggest.rename.note.shared', { file: note.file }) : t('tools.suggest.rename.note.sounds', { file: note.file, sound: note.sound }))}
      </List>
      {isEmptyPlan(plan) && <p class="tool-note">{t('tools.suggest.rename.nothing')}</p>}
      <p class="tool-note">{t('tools.suggest.rename.undo')}</p>
      <div class="tool-row">
        <button type="button" class="tool-button" data-action="repair-apply" disabled={busy || readOnly || isEmptyPlan(plan)} onClick={() => void repair.apply(pack)}>
          {t('tools.suggest.rename.apply')}
        </button>
        <button type="button" class="tool-button" data-action="repair-dismiss" disabled={busy} onClick={() => repair.dismiss()}>
          {t('tools.suggest.rename.dismiss')}
        </button>
      </div>
    </div>
  );
}

/**
 * The bar of the checks tab for files with bad paths: nothing while there are none and no
 * report to show. It stays mounted for the tab's life, so the report of what it did outlives
 * the findings it removed (and goes when the pack has bad paths again: an undo).
 *
 * @param pack the open pack
 * @param files how many files the checks find with a path Minecraft refuses
 * @param readOnly the pack is only shown (generated by the converter): nothing can be applied
 * @param run applies a command that renames and puts files (app/session `run`)
 */
export function PathRepair({ pack, files, readOnly, run }: { pack: RepairPack; files: number; readOnly: boolean; run: RunCommand }) {
  const repair = useRef<Repair | null>(null);
  repair.current ??= createRepair(run);
  const current = repair.current;
  // another pack: the plan was for the previous one
  useEffect(() => () => current.dismiss(), [pack, current]);
  const state = current.state.value;
  const running = current.running.value;
  const report = state.phase === 'done' && files === 0;
  if (files === 0 && state.phase !== 'plan' && state.phase !== 'failed' && !report) return null;
  return (
    <div class="suggest-repair" data-testid="repair-paths" data-phase={running !== null ? 'running' : state.phase} data-bad={files}>
      {files > 0 && (
        <div class="tool-row">
          <button type="button" class="tool-button" data-action="repair-review" disabled={readOnly || running !== null} onClick={() => void current.review(pack)}>
            {t('tools.suggest.rename.run')}
          </button>
          <span class="tool-note">{t('tools.suggest.rename.bar', { count: files })}</span>
        </div>
      )}
      {state.phase === 'plan' && <Plan plan={state.plan} changed={state.changed} repair={current} pack={pack} busy={running !== null} readOnly={readOnly} />}
      {running !== null && <PythonProgress running={running} />}
      {report && state.phase === 'done' && (
        <p class="tool-note" role="status" data-testid="repair-done">
          {t('tools.suggest.rename.done', { files: state.files, refs: state.refs })}
        </p>
      )}
      {state.phase === 'failed' && (
        <div class="suggest-error" role="alert" data-testid="repair-error">
          <p class="tool-note tool-warning">{state.said.text}</p>
          {state.said.detail !== null && (
            <details>
              <summary class="tool-note">{t('tools.suggest.detail')}</summary>
              <pre>{state.said.detail}</pre>
            </details>
          )}
        </div>
      )}
    </div>
  );
}
