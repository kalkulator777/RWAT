/**
 * The markup tools (docs/proposals/editor.md §3.9): what one is and how the editor finds
 * them. Tools register themselves the way panels do (app/registry.ts): every folder
 * `src/tools/<name>/` has an `index.ts` whose default export is one {@link ToolDef}, and
 * ./index.ts finds the folders by itself (`import.meta.glob('./*\/index.ts')`). A new
 * tool edits no shared file.
 *
 * ```ts
 * // src/tools/doors/index.ts
 * import { defineTool } from '../registry';
 * import { startDoors } from './session';
 * export default defineTool({
 *   id: 'doors', order: 20, title: 'tools.doors.title', hint: 'tools.doors.hint',
 *   fields: ['/doors/*'],
 *   activate: (context) => startDoors(context),
 * });
 * ```
 *
 * A tool works on the open wagon — a type paired with a model ({@link ToolSubject}) — in
 * the OBJ frame, as the file has its markup (`x-frame: obj`, R6). It turns gestures in the
 * 3D view into journal commands (§3.4): it reads the type's JSON and writes nothing but
 * through {@link ToolContext.dispatch}. Everything it does by mouse it also does by keyboard
 * in its section of the inspector ({@link ToolSession.Inspector}, §6.3). It draws through
 * the view's overlay layers and takes the view's presses and picks ({@link ToolView}); when
 * it is turned off it takes all of that back ({@link ToolSession.dispose}).
 *
 * Every spatial field of the wagon type's schema (`x-frame`) has a tool that edits it
 * ({@link ToolDef.fields}, {@link framedFields}): the forms show such a field as a summary
 * and the tool edits it (registry.test.ts holds the list of fields still waiting for theirs).
 */

import type { ReadonlySignal, Signal } from '@preact/signals';
import type { ComponentType } from 'preact';
import type { Command, Link, LoadedModel, ViewApi } from '../core/contracts';
import type { FieldDescriptor } from '../core/schema';
import type { WagonType } from '../ports/wagonType';
import type { CameraView } from '../view3d/cameras';
import type { ViewDragger, ViewPointer } from '../view3d/state';

export type { ViewDragger, ViewPointer };

/** The 3D view as a tool drives it: `ViewApi` (overlays, picks) and, beyond it, the camera and the left button's presses. */
export interface ToolView extends ViewApi {
  /** Switches the camera to a view (the floor tool works from the top). */
  setCamera(camera: CameraView): void;
  /** Takes the presses of the left button from the camera (null: gives them back); one tool at a time. */
  setDragger(dragger: ViewDragger | null): void;
}

/** What a tool works on: the open wagon, a type paired with a model, as the pack holds it now. */
export interface ToolSubject {
  /** The wagon's id `<namespace>:<name>`: the `type` of the zone, door and seat links (core/contracts `Link`). */
  readonly wagon: string;
  /** The type's pack path: `data/<namespace>/wagon_types/<name>.json`. */
  readonly typeFile: string;
  /** The model's pack path: `assets/<namespace>/wagon_models/<name>.json`. */
  readonly modelFile: string;
  /** The type's JSON as it stands; shared with the pack: never change it in place. */
  readonly typeJson: unknown;
  /** The type as the engine reads it (ports/wagonType, model frame); null when it does not load. */
  readonly type: WagonType | null;
  /** The model as the 3D view shows it (OBJ frame); null while it is being read. */
  readonly model: LoadedModel | null;
  /** True for a pack the editor only shows (generated by the converter): its commands are refused. */
  readonly readOnly: boolean;
}

/** What a tool is given when it is turned on. */
export interface ToolContext {
  /**
   * The open wagon as it stands: a new value after every edit of the pack and when the
   * model has been read. Never null while the tool is on: a tool is turned off before the
   * wagon closes or another opens, and turned on afresh for the next one.
   */
  readonly subject: ReadonlySignal<ToolSubject | null>;
  /** Applies a command through the journal (undo, redo, autosave); false when it was refused. */
  dispatch(command: Command): boolean;
  /** The editor's one selection: zones, doors and chairs are `{kind, type: subject.wagon, index}` links. */
  readonly selection: Signal<readonly Link[]>;
  readonly view: ToolView;
  /**
   * The doors the preview shows open, as the engine's open-door bits (bit i: door i of the
   * type, open or opening); null while there is no preview of this wagon.
   */
  readonly previewDoors: ReadonlySignal<number | null>;
}

/** A tool while it is on. */
export interface ToolSession {
  /**
   * The tool's section of the inspector, shown above the selected file's form while the
   * tool is on: its numbers, choices and buttons — all a gesture does, by keyboard.
   */
  readonly Inspector: ComponentType;
  /** Turns the tool off: its overlay layers emptied, its pick listeners and dragger given back. */
  dispose(): void;
}

/** A markup tool as its folder declares it. */
export interface ToolDef {
  /** Unique across the editor, lower-case words joined by '-': `floor`, `doors`, `seats`. */
  id: string;
  /** Ascending in the view's tool bar, ties by id. */
  order: number;
  /** i18n key of the tool's name (the tool's own `i18n.ts`, in ru and en): its button and its section's heading. */
  title: string;
  /** i18n key of what the tool does, a line: the button's tooltip. */
  hint: string;
  /**
   * The places in the wagon type's JSON the tool edits, as JSON pointers where `*` stands
   * for any element of a list: `/interior`, `/interior/*`, `/doors/*`. A place covers
   * everything inside it. Each spatial (`x-frame`) field of the schema is covered by one tool.
   */
  fields: readonly string[];
  /** Whether the tool can work on the open wagon; any type paired with a model when left out. */
  applies?(subject: ToolSubject): boolean;
  /** Turns the tool on for the open wagon. */
  activate(context: ToolContext): ToolSession;
}

/** A tool folder's `index.ts` as `import.meta.glob(..., { eager: true })` returns it. */
export interface ToolModule {
  default?: ToolDef;
}

/** Declares a tool; it only gives the declaration its type. */
export function defineTool(def: ToolDef): ToolDef {
  return def;
}

const ID = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

/** The segments of a field pattern (`/cab/seats/*\/at` → `cab`, `seats`, `*`, `at`); a pattern is `''` or starts with '/'. */
function segmentsOf(pattern: string): string[] | null {
  if (pattern === '') return [];
  if (!pattern.startsWith('/')) return null;
  return pattern.slice(1).split('/');
}

/**
 * True if the tool's place `pattern` covers `pointer`: each of its segments is the
 * pointer's, `*` standing for any one, and the pointer may go on below it. `pointer` is a
 * place of a file (`/interior/2/min`) or a pattern itself (`/interior/*`).
 */
export function covers(pattern: string, pointer: string): boolean {
  const mine = segmentsOf(pattern);
  const theirs = segmentsOf(pointer);
  if (mine === null || theirs === null || mine.length > theirs.length) return false;
  return mine.every((segment, i) => segment === '*' || segment === theirs[i]);
}

/** The tool that edits a place of the wagon type (`/interior/2`, `/doors/*`), or undefined. */
export function toolFor(tools: readonly ToolDef[], pointer: string): ToolDef | undefined {
  return tools.find((tool) => tool.fields.some((pattern) => covers(pattern, pointer)));
}

/** A pointer segment as RFC 6901 writes it. */
function escaped(key: string): string {
  return key.replaceAll('~', '~0').replaceAll('/', '~1');
}

/**
 * The places of the schema's spatial fields (`x-frame`) in a file of the schema, as field
 * patterns: a list's element or a dictionary's value is `*`, the forms of a `oneOf` are
 * the place itself (`interior`: a list of zones, or one zone in the old form). What is
 * inside a spatial field is its own: the walk does not go on below one. Sorted.
 */
export function framedFields(root: FieldDescriptor): string[] {
  const found = new Set<string>();
  const walk = (field: FieldDescriptor, pointer: string, seen: ReadonlySet<FieldDescriptor>): void => {
    if (seen.has(field)) return;
    if (field.frame !== undefined) {
      found.add(pointer);
      return;
    }
    const next = new Set(seen).add(field);
    for (const property of field.properties ?? []) walk(property, `${pointer}/${escaped(property.key ?? '')}`, next);
    for (const variant of field.variants ?? []) walk(variant, pointer, next);
    if (field.items !== undefined) walk(field.items, `${pointer}/*`, next);
    if (field.values !== undefined) walk(field.values, `${pointer}/*`, next);
  };
  walk(root, '', new Set());
  return [...found].sort();
}

/**
 * The tools the modules declare, sorted by order and id. A broken declaration (no default
 * export, a bad or repeated id, no title or hint, a field pattern that is not a pointer,
 * a place two tools claim) throws with every problem listed, as the panels' registry does:
 * the editor does not start half-registered, and the unit test of a new tool fails at once.
 */
export function collectTools(modules: Readonly<Record<string, ToolModule>>): ToolDef[] {
  const problems: string[] = [];
  const tools: ToolDef[] = [];
  const seen = new Map<string, string>();
  const claims: { pattern: string; where: string }[] = [];
  for (const path of Object.keys(modules).sort()) {
    const def = modules[path]?.default;
    if (def === undefined) {
      problems.push(`${path}: no default export of defineTool(...)`);
      continue;
    }
    const where = `${path}: tool '${String(def.id)}'`;
    if (typeof def.id !== 'string' || !ID.test(def.id)) problems.push(`${where}: id must be lower-case words joined by '-'`);
    if (typeof def.title !== 'string' || def.title === '') problems.push(`${where}: no title key`);
    if (typeof def.hint !== 'string' || def.hint === '') problems.push(`${where}: no hint key`);
    if (!Number.isFinite(def.order)) problems.push(`${where}: order must be a finite number`);
    if (typeof def.activate !== 'function') problems.push(`${where}: no activate`);
    if (def.applies !== undefined && typeof def.applies !== 'function') problems.push(`${where}: applies is not a function`);
    if (!Array.isArray(def.fields)) problems.push(`${where}: fields must be a list of pointers`);
    for (const pattern of Array.isArray(def.fields) ? def.fields : []) {
      if (typeof pattern !== 'string' || !pattern.startsWith('/')) {
        problems.push(`${where}: field '${String(pattern)}' is not a pointer`);
        continue;
      }
      const clash = claims.find((claim) => covers(claim.pattern, pattern) || covers(pattern, claim.pattern));
      if (clash !== undefined) problems.push(`${where}: field '${pattern}' is already ${clash.where}'s ('${clash.pattern}')`);
      claims.push({ pattern, where: `tool '${def.id}'` });
    }
    const first = seen.get(def.id);
    if (first !== undefined) problems.push(`${where}: id already used in ${first}`);
    else seen.set(def.id, path);
    tools.push(def);
  }
  if (problems.length > 0) throw new Error(`Tool registration failed:\n${problems.join('\n')}`);
  return tools.sort((a, b) => a.order - b.order || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}
