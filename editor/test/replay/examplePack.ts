/**
 * A place of the result: a file and a JSON pointer in it ('' — the whole file), and the
 * repository's file it is compared with when that has another path (a wagon renamed later).
 */
export type Place = readonly [file: string, at: string, repository?: string];

export interface Step {
  /** The scenario's section (editor.md §2.x) and what the user does. */
  name: string;
  /** What of the result the step makes, compared with the repository's files right after it. */
  makes: readonly Place[];
  /** TODO(gap): the step writes JSON itself, because the editor has no way to do it; says what is missing. */
  gap?: string;
  run(studio: Studio): Promise<void>;
}

/** The user's own files: the example pack's folder on the disk, which the generator writes. */
function disk(...paths: string[]): string[] {
  return paths.map((path) => join(EXAMPLE_PACK, ...path.split('/')));
}

/** Files of a folder of the example pack, by their names. */
function inFolder(folder: string, ...names: string[]): string[] {
  return disk(...names.map((name) => `${folder}/${name}`));
}

