// ---------------------------------------------------------------------------- the steps

async function markFloor(studio: Studio, id: string, zones: readonly ZoneJson[], name: 'coach' | 'shunter'): Promise<void> {
  await studio.openWagon(id);
  const { session, bench } = studio.tool<FloorSession>('floor');
  await studio.gestures(() => drawZones(bench, session.tool, id, zones, ZONE_FLOORS[name]));
  studio.noTool();
}

async function markDoors(studio: Studio, id: string, namings: readonly DoorNaming[], name: 'coach' | 'shunter'): Promise<void> {
  await studio.openWagon(id);
  const { session, bench } = studio.tool<DoorsSession>('doors');
  await studio.gestures(() => makeDoors(bench, session.tool, id, doors(namings), DOOR_STEPS[name]));
  studio.noTool();
}

