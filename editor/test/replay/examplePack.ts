/** The doors as tools/scenarios.node.ts `makeDoors` takes them: it names and flags each; the box is its steps'. */
function doors(namings: readonly DoorNaming[]): DoorJson[] {
  return namings.map((naming) => ({ min: [0, 0, 0], max: [0, 0, 0], ...naming }));
}

/** The shunter's chairs: where each cushion is clicked is CHAIR_CLICKS'; the yaw typed — the second driver looks back. */
