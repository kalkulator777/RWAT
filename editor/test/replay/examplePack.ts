/**
 * The example pack made from scratch in the editor (docs/proposals/editor.md §1.4 item 1,
 * M5): an empty new pack, the files a user has — the OBJ, MTL, PNG and `.anim` the
 * generator writes (`tools/gen_example_pack.py`), the README, the licence and the icon —
 * and, from them, everything else made by the editor's own dialogs, forms, markup tools,
 * names tab and sounds tab: `pack.mcmeta` with its `rwat` block, three wagons with their
 * physics, floor, doors, driver's chairs, liveries, door animation, handbrake and sounds, a
 * rail style, the names in English and Russian. No declaration is read: the answers below
 * are what the user types, picks and drags.
 *
 * Read top to bottom it is the scenario of §2.1–§2.5 as the help tells it (src/help/),
 * each step one thing the user does. A step says which places of the result it makes; the
 * test (./examplePack.test.ts) compares them with the repository's files right after it,
 * so a broken step fails by its name with the difference of the JSON. A step that has to
 * write JSON itself, because the editor cannot do it, carries `gap` (TODO(gap)) and is
 * counted: their number may only go down.
 */

