package com.muzhik17.trainsmod.pack;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.FileNotFoundException;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

import org.junit.jupiter.api.Test;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.muzhik17.trainsmod.client.render.model.WagonModelDecl;

/**
 * The generated packs in {@code run/rwat_packs} (MVP) load as the game loads
 * them, strictly: no errors, and no key the parsers don't know — the
 * converter and the parsers agree on the format. The warnings that remain
 * are printed. The packs are generated by {@code tools/ir2rwat.py}; without
 * them this is skipped.
 */
class GeneratedPackLoadTest {

    private static final Path PACKS = Path.of("run/rwat_packs");

    /** One file of a pack: its namespace, its id, its origin as the game names it. */
    private record PackFile(Path path, String namespace, String id, PackOrigin origin) {
    }

    /** Every {@code <root>/<ns>/<folder>/<id>.json} of every pack. */
    private static List<PackFile> files(String root, String folder) throws IOException {
        assumeTrue(Files.isDirectory(PACKS), "no generated packs in " + PACKS);
        List<PackFile> files = new ArrayList<>();
        try (Stream<Path> packs = Files.list(PACKS)) {
            for (Path pack : packs.filter(Files::isDirectory).sorted().toList()) {
                try (Stream<Path> walk = Files.walk(pack)) {
                    for (Path path : walk.sorted().toList()) {
                        String relative = pack.relativize(path).toString().replace('\\', '/');
                        String[] parts = relative.split("/");
                        if (parts.length == 4 && parts[0].equals(root) && parts[2].equals(folder)
                                && parts[3].endsWith(".json")) {
                            String id = parts[1] + ":" + parts[3].substring(0, parts[3].length() - 5);
                            files.add(new PackFile(path, parts[1], id,
                                    new PackOrigin("rwat/" + pack.getFileName(), relative)));
                        }
                    }
                }
            }
        }
        assumeTrue(!files.isEmpty(), "no " + folder + " in " + PACKS);
        return files;
    }

    private static JsonObject json(PackFile file) throws IOException {
        return JsonParser.parseString(Files.readString(file.path(), StandardCharsets.UTF_8)).getAsJsonObject();
    }

    private static void print(String what, List<PackProblem> problems) {
        System.out.println(what + ": " + problems.size() + " problem(s)");
        problems.forEach(problem -> System.out.println("  " + problem));
    }

    private static String lines(List<PackProblem> problems) {
        return "\n  " + String.join("\n  ", problems.stream().map(PackProblem::toString).toList());
    }

    @Test
    void wagonTypesLoadWithoutErrorsOrUnknownKeys() throws IOException {
        List<WagonTypeLoader.Declaration> declarations = new ArrayList<>();
        for (PackFile file : files("data", "wagon_types")) {
            declarations.add(new WagonTypeLoader.Declaration(file.id(), file.origin(), json(file)));
        }
        WagonTypeLoader.Result result = WagonTypeLoader.load(declarations);
        print("wagon types", result.problems());
        List<PackProblem> bad = result.problems().stream()
                .filter(p -> p.isError() || p.message().startsWith("unknown key")).toList();
        assertTrue(bad.isEmpty(), lines(bad));
        assertEquals(declarations.size(), result.types().size());
    }

    @Test
    void modelsAndRailStylesParseWithoutWarnings_everyModelHasItsType() throws IOException {
        List<PackProblem> problems = new ArrayList<>();
        Map<String, PackOrigin> models = new HashMap<>();
        for (PackFile file : files("assets", "wagon_models")) {
            try {
                WagonModelDecl.parse(file.namespace(), json(file), w -> problems.add(file.origin().warning(w)));
                models.put(file.id(), file.origin());
            } catch (RuntimeException e) {
                problems.add(file.origin().error(e.getMessage()));
            }
        }
        for (PackFile file : files("assets", "rail_models")) {
            try {
                RailStyleDecl.parse(file.namespace(), json(file), w -> problems.add(file.origin().warning(w)));
            } catch (RuntimeException e) {
                problems.add(file.origin().error(e.getMessage()));
            }
        }
        List<String> typeIds = files("data", "wagon_types").stream().map(PackFile::id).toList();
        problems.addAll(PackReport.modelsWithoutType(models, new HashSet<>(typeIds)));
        print("wagon models and rail styles", problems);
        assertTrue(problems.isEmpty(), lines(problems));
    }

    /** {@code /rwatc packs validate} over the packs on disk: every model's files there and readable. */
    @Test
    void everyModelsFilesAreThere() throws IOException {
        List<PackFile> modelFiles = files("assets", "wagon_models");
        ModelCheck.Files files = new ModelCheck.Files() {
            private Path resolve(String location) {
                int colon = location.indexOf(':');
                for (PackFile model : modelFiles) {
                    Path assets = model.path().getParent().getParent().getParent();
                    Path file = assets.resolve(location.substring(0, colon)).resolve(location.substring(colon + 1));
                    if (Files.isRegularFile(file)) {
                        return file;
                    }
                }
                return null;
            }

            @Override
            public boolean valid(String location) {
                return ResourceLocations.valid(location);
            }

            @Override
            public boolean exists(String location) {
                return resolve(location) != null;
            }

            @Override
            public InputStream open(String location) throws IOException {
                Path file = resolve(location);
                if (file == null) {
                    throw new FileNotFoundException(location);
                }
                return Files.newInputStream(file);
            }
        };
        List<PackProblem> problems = new ArrayList<>();
        for (PackFile file : modelFiles) {
            problems.addAll(ModelCheck.check(WagonModelDecl.parse(file.namespace(), json(file)), file.origin(), files));
        }
        print("model files", problems);
        List<PackProblem> errors = problems.stream().filter(PackProblem::isError).toList();
        assertTrue(errors.isEmpty(), lines(errors));
    }
}
