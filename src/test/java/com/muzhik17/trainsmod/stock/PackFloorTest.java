package com.muzhik17.trainsmod.stock;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.TestFactory;

import com.google.gson.JsonParser;
import com.muzhik17.trainsmod.kinematics.FloorCheck;
import com.muzhik17.trainsmod.pack.PackOrigin;
import com.muzhik17.trainsmod.pack.RwatPackMeta;
import com.muzhik17.trainsmod.pack.WagonTypeLoader;

/**
 * Every wagon type of the RWAT packs in {@code run/rwat_packs} parses and
 * has a floor a player can actually walk (SPEC §9.6, {@link FloorCheck}):
 * one test per type, each listing all of its problems.
 *
 * <p>The types are read as the game reads them: the pack's {@code rwat}
 * block first ({@link RwatPackMeta}) — a pack the game would leave out, or
 * one of another format than 1, fails its types here instead of being read
 * as format 1 — then each type file whole through the type loader
 * ({@link WagonTypeLoader}, the parser the registry uses), its markup in the
 * OBJ frame of format 1 turned into the model frame.
 *
 * <p>The packs are in the repository: the example pack for good (CC0,
 * {@code tools/gen_example_pack.py}), the MVP pack generated by
 * {@code tools/ir2rwat.py packs/mvp.json} until it leaves it (roadmap R12).
 * With no pack folder there this is skipped, not passed.
 */
class PackFloorTest {

    private static final Path PACKS = Path.of("run/rwat_packs");

    /** One wagon type file of a pack folder: the pack, its id ({@code rwat/<folder>}), the type's id. */
    private record TypeFile(Path pack, String packId, Path path, String id) {
    }

    @TestFactory
    Stream<DynamicTest> everyTypeHasAWalkableFloor() throws IOException {
        assumeTrue(Files.isDirectory(PACKS), "no packs in " + PACKS);
        List<TypeFile> types = new ArrayList<>();
        try (Stream<Path> packs = Files.list(PACKS)) {
            for (Path pack : packs.filter(Files::isDirectory).sorted().toList()) {
                try (Stream<Path> files = Files.walk(pack)) {
                    files.filter(p -> pack.relativize(p).toString().replace('\\', '/')
                                    .matches("data/[^/]+/wagon_types/[^/]+\\.json"))
                            .sorted()
                            .forEach(p -> types.add(new TypeFile(pack, "rwat/" + pack.getFileName(), p, id(p))));
                }
            }
        }
        assumeTrue(!types.isEmpty(), "no wagon types in " + PACKS);
        return types.stream().map(file -> DynamicTest.dynamicTest(file.id(), () -> {
            RwatPackMeta.Result meta = RwatPackMeta.read(file.pack(), file.packId());
            assertTrue(meta.accepted(), file.packId() + " isn't loaded by the game: " + meta.problems());
            assertEquals(1, meta.meta().format(), file.packId() + ": this reads format 1");
            WagonTypeLoader.Result loaded = WagonTypeLoader.load(List.of(new WagonTypeLoader.Declaration(file.id(),
                    new PackOrigin(file.packId(), file.pack().relativize(file.path()).toString().replace('\\', '/')),
                    JsonParser.parseString(Files.readString(file.path(), StandardCharsets.UTF_8)))));
            WagonType type = loaded.types().get(file.id());
            assertNotNull(type, file.id() + " isn't loaded: " + loaded.problems());
            List<String> problems = FloorCheck.problems(type);
            assertTrue(problems.isEmpty(), file.id() + ":\n  " + String.join("\n  ", problems));
        }));
    }

    /** {@code <ns>:<id>} from {@code …/data/<ns>/wagon_types/<id>.json}. */
    private static String id(Path path) {
        String namespace = path.getParent().getParent().getFileName().toString();
        String file = path.getFileName().toString();
        return namespace + ":" + file.substring(0, file.length() - ".json".length());
    }
}
