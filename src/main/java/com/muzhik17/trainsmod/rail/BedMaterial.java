package com.muzhik17.trainsmod.rail;

import java.util.Arrays;
import java.util.List;

import com.muzhik17.trainsmod.path.RailSegment;

import net.minecraft.network.chat.Component;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.material.MapColor;

/**
 * What the track bed under a segment is made of (SPEC §2.2): the material
 * picked in the rails item's screen. Each material is a {@link TrackBedBlock}
 * of its own, textured like a vanilla block and sounding like it; the
 * invisible one draws nothing and is still walked on.
 *
 * <p>The bed's models and blockstates are generated by
 * {@code tools/gen_track_bed.py} — a material added here needs its line there.
 */
public enum BedMaterial {

    GRAVEL("gravel", Blocks.GRAVEL, SoundType.GRAVEL),
    COARSE_DIRT("coarse_dirt", Blocks.COARSE_DIRT, SoundType.GRAVEL),
    DIRT("dirt", Blocks.DIRT, SoundType.GRAVEL),
    SAND("sand", Blocks.SAND, SoundType.SAND),
    STONE("stone", Blocks.STONE, SoundType.STONE),
    COBBLESTONE("cobblestone", Blocks.COBBLESTONE, SoundType.STONE),
    ANDESITE("andesite", Blocks.ANDESITE, SoundType.STONE),
    SMOOTH_STONE("smooth_stone", Blocks.SMOOTH_STONE, SoundType.STONE),
    STONE_BRICKS("stone_bricks", Blocks.STONE_BRICKS, SoundType.STONE),
    GRAY_CONCRETE("gray_concrete", Blocks.GRAY_CONCRETE, SoundType.STONE),
    OAK_PLANKS("oak_planks", Blocks.OAK_PLANKS, SoundType.WOOD),
    SPRUCE_PLANKS("spruce_planks", Blocks.SPRUCE_PLANKS, SoundType.WOOD),
    /** No visible bed: the rails seem to lie on whatever is around, the bed still carries the player. */
    INVISIBLE("invisible", null, SoundType.STONE);

    /** The bed's hardness, whatever it is made of — breaking any bed block takes the whole segment. */
    private static final float STRENGTH = 1.5F;

    private final String id;
    private final Block look;
    private final SoundType sound;

    BedMaterial(String id, Block look, SoundType sound) {
        this.id = id;
        this.look = look;
        this.sound = sound;
    }

    /** The id segments, items and commands use. */
    public String id() {
        return id;
    }

    /** The id as segments and items store it: {@link RailSegment#DEFAULT_BED} for gravel. */
    public String key() {
        return this == GRAVEL ? RailSegment.DEFAULT_BED : id;
    }

    public boolean invisible() {
        return look == null;
    }

    /** The bed block's registry name; gravel keeps the plain name it had before materials. */
    public String blockName() {
        return this == GRAVEL ? "track_bed" : "track_bed_" + id;
    }

    /** The name shown in the picker: the vanilla block's own. */
    public Component displayName() {
        return look == null
                ? Component.translatable("bed.railswheelsandtrains.invisible")
                : Component.translatable(look.getDescriptionId());
    }

    /** The picker icon: the vanilla block, a barrier for the invisible bed. */
    public ItemStack icon() {
        return new ItemStack(look == null ? Items.BARRIER : look.asItem());
    }

    /** The bed block's properties: sound and map colour of the look-alike, one hardness for all. */
    public BlockBehaviour.Properties properties() {
        BlockBehaviour.Properties properties = BlockBehaviour.Properties.of()
                .strength(STRENGTH)
                .sound(sound)
                .noOcclusion();
        if (look == null) {
            return properties.mapColor(MapColor.NONE).noTerrainParticles();
        }
        return properties.mapColor(look.defaultMapColor());
    }

    /** The material of a stored id, null if there is none by that id. */
    public static BedMaterial byId(String id) {
        if (id.isEmpty()) {
            return GRAVEL;
        }
        for (BedMaterial material : values()) {
            if (material.id.equals(id)) {
                return material;
            }
        }
        return null;
    }

    /** The material a segment's bed is laid in: an unknown id lays the default gravel. */
    public static BedMaterial of(String id) {
        BedMaterial material = byId(id);
        return material == null ? GRAVEL : material;
    }

    public static List<String> ids() {
        return Arrays.stream(values()).map(BedMaterial::id).toList();
    }
}
